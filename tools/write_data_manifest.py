"""Write data/manifest.toml from the download logs: every file's URL, SHA-256, size and date.

Usage:
    python tools/write_data_manifest.py

Reads data/raw/miso/downloads.jsonl (written by tools/fetch_miso_prices.py) and keeps the
latest record per file. Hold-out files are listed with their metadata only (URL, hash,
size); their contents are never read (CLAUDE.md §7.2). The manifest is committed to git as
the provenance record (CLAUDE.md §5.4); the files themselves are not.
"""

import datetime
import json
from pathlib import Path

DOWNLOAD_LOG_PATHS = [Path("data/raw/miso/downloads.jsonl")]
MANIFEST_PATH = Path("data/manifest.toml")


def toml_string(value):
    return json.dumps(value, ensure_ascii=False)


def main():
    latest_record_by_file = {}
    for log_path in DOWNLOAD_LOG_PATHS:
        for line in log_path.read_text(encoding="utf-8").splitlines():
            if line.strip():
                record = json.loads(line)
                latest_record_by_file[record["file_name"]] = record
    lines = [
        "# Provenance of every downloaded data file (CLAUDE.md §5.4).",
        f"# Generated by tools/write_data_manifest.py on {datetime.date.today().isoformat()}.",
        "# status: downloaded | missing (HTTP 404) | failed",
        "",
    ]
    for file_name in sorted(latest_record_by_file):
        record = latest_record_by_file[file_name]
        lines.append("[[file]]")
        lines.append(f"name = {toml_string(file_name)}")
        lines.append(f"source = {toml_string('miso')}")
        lines.append(f"url = {toml_string(record['url'])}")
        lines.append(f"market = {toml_string(record['market'])}")
        lines.append(f"first_operating_day = {record['first_operating_day']}")
        lines.append(f"last_operating_day = {record['last_operating_day']}")
        lines.append(f"is_holdout = {'true' if record['is_holdout'] else 'false'}")
        lines.append(f"status = {toml_string(record['status'])}")
        lines.append(f"retrieved_at_utc = {record['retrieved_at_utc'].replace('+00:00', 'Z')}")
        if record["status"] == "downloaded":
            lines.append(f"sha256 = {toml_string(record['sha256'])}")
            lines.append(f"size_bytes = {record['size_bytes']}")
        lines.append("")
    MANIFEST_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(latest_record_by_file)} files in {MANIFEST_PATH}")


if __name__ == "__main__":
    main()
