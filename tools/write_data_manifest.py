"""Write data/manifest.toml from the download logs: every file's URL, SHA-256, size and date.

Usage:
    python tools/write_data_manifest.py

Reads data/raw/miso/downloads.jsonl (written by tools/fetch_miso_prices.py) and
data/raw/series/downloads.jsonl (written by tools/fetch_series.py, round 28), and keeps the
latest record per file. The weather forecasts keep their own log
(data/raw/nws/downloads.jsonl, ~70,000 small files) and are summarised when parsed (M1).
Hold-out files are listed with their metadata only (URL, hash, size); their contents are
never read (docs/design_spec.md §7.2). The manifest is committed to git as the provenance record
(docs/design_spec.md §5.4); the files themselves are not.
"""

import datetime
import json
from pathlib import Path

MISO_DOWNLOAD_LOG_PATH = Path("data/raw/miso/downloads.jsonl")
SERIES_DOWNLOAD_LOG_PATH = Path("data/raw/series/downloads.jsonl")
MANIFEST_PATH = Path("data/manifest.toml")


def toml_string(value):
    return json.dumps(value, ensure_ascii=False)


def main():
    latest_record_by_file = {}
    for line in MISO_DOWNLOAD_LOG_PATH.read_text(encoding="utf-8").splitlines():
        if line.strip():
            record = json.loads(line)
            latest_record_by_file[record["file_name"]] = record
    series_records = []
    if SERIES_DOWNLOAD_LOG_PATH.exists():
        series_records = [
            json.loads(line)
            for line in SERIES_DOWNLOAD_LOG_PATH.read_text(encoding="utf-8").splitlines()
            if line.strip() and json.loads(line)["status"] == "downloaded"
        ]
    lines = [
        "# Provenance of every downloaded data file (docs/design_spec.md §5.4).",
        f"# Generated by tools/write_data_manifest.py on {datetime.date.today().isoformat()}.",
        "# status: downloaded | missing (HTTP 404) | failed",
        "",
    ]
    for file_name in sorted(latest_record_by_file):
        record = latest_record_by_file[file_name]
        lines.append("[[file]]")
        lines.append(f"name = {toml_string(file_name)}")
        lines.append(f"source = {toml_string('miso')}")
        lines.append(f"url = {toml_string(record['url'])}")
        lines.append(f"market = {toml_string(record['market'])}")
        lines.append(f"first_operating_day = {record['first_operating_day']}")
        lines.append(f"last_operating_day = {record['last_operating_day']}")
        lines.append(f"is_holdout = {'true' if record['is_holdout'] else 'false'}")
        lines.append(f"status = {toml_string(record['status'])}")
        lines.append(f"retrieved_at_utc = {record['retrieved_at_utc'].replace('+00:00', 'Z')}")
        if record["status"] == "downloaded":
            lines.append(f"sha256 = {toml_string(record['sha256'])}")
            lines.append(f"size_bytes = {record['size_bytes']}")
        lines.append("")
    for record in sorted(series_records, key=lambda record: record["file_name"]):
        lines.append("[[file]]")
        lines.append(f"name = {toml_string(record['file_name'])}")
        lines.append(f"source = {toml_string(record['source'])}")
        lines.append(f"url = {toml_string(record['url'])}")
        lines.append(f"status = {toml_string(record['status'])}")
        lines.append(f"retrieved_at_utc = {record['retrieved_at_utc'].replace('+00:00', 'Z')}")
        lines.append(f"sha256 = {toml_string(record['sha256'])}")
        lines.append(f"size_bytes = {record['size_bytes']}")
        lines.append("")
    MANIFEST_PATH.write_text("\n".join(lines), encoding="utf-8")
    miso_count, series_count = len(latest_record_by_file), len(series_records)
    print(f"{miso_count} MISO and {series_count} series files in {MANIFEST_PATH}")


if __name__ == "__main__":
    main()
